package gen

import (
	"fmt"
	"strings"
)

// driverTemplate is the gc reference driver: one static core implementing
// the obs* API and a reflection serializer emitting a
// grossmith-observation-v2 document on stdout, plus a generated main that
// calls the subject and hands over POINTERS to the results (the pointer
// trick keeps each result's STATIC type — reflect on a boxed interface
// value would otherwise report the dynamic type and erase the interface).
//
// The driver is adapter territory: it may import the standard library; the
// subject may not. It builds standalone (case dirs live outside the
// grossmith module), so the panic-kind mapping and serialization are
// embedded rather than imported from grossmith/observe — the document is
// the contract, not the code.
const driverCore = `// Code generated by grossmith. The reference observation driver:
// emits a grossmith-observation-v2 document on stdout. See
// docs/2026-08-06_observation-protocol-and-adapters.md.

package main

import (
	_gjson "encoding/json"
	_gfmt "fmt"
	_gos "os"
	_greflect "reflect"
	_gsort "sort"
	_gstrings "strings"
)

var _gEvents = []map[string]any{}

func _gEventValue(at, goType, kind string, payload map[string]any) {
	v := map[string]any{"kind": kind, "goType": goType}
	for k, val := range payload {
		v[k] = val
	}
	_gEvents = append(_gEvents, map[string]any{"at": at, "value": v})
}

func obsBool(at, goType string, v bool) {
	_gEventValue(at, goType, "bool", map[string]any{"bool": v})
}

func obsInt(at, goType string, v int64) {
	_gEventValue(at, goType, "int", map[string]any{"int": v})
}

func obsUint(at, goType string, v uint64) {
	_gEventValue(at, goType, "uint", map[string]any{"uint": v})
}

func obsStr(at, goType string, v string) {
	_gEventValue(at, goType, "string", map[string]any{"str": v})
}

func obsRecovered(msg string) {
	_gEvents = append(_gEvents, map[string]any{"at": "recovered",
		"panic": map[string]any{"kind": _gPanicKind(msg), "message": msg}})
}

func _gPanicKind(msg string) string {
	switch {
	case _gstrings.Contains(msg, "integer divide by zero"):
		return "divide"
	case _gstrings.Contains(msg, "index out of range"):
		return "index-out-of-range"
	case _gstrings.Contains(msg, "slice bounds out of range"):
		return "slice-bounds"
	case _gstrings.Contains(msg, "interface conversion"):
		return "interface-conversion"
	case _gstrings.Contains(msg, "nil pointer dereference"),
		_gstrings.Contains(msg, "invalid memory address"):
		return "nil-dereference"
	}
	return "other"
}

func _gGoType(t _greflect.Type) string {
	return _gstrings.ReplaceAll(t.String(), "main.", "")
}

// _gValue serializes one value from a POINTER (static type preserved).
func _gValue(ptr any) map[string]any {
	return _gReflect(_greflect.ValueOf(ptr).Elem())
}

func _gReflect(v _greflect.Value) map[string]any {
	goType := _gGoType(v.Type())
	switch v.Kind() {
	case _greflect.Bool:
		return map[string]any{"kind": "bool", "goType": goType, "bool": v.Bool()}
	case _greflect.Int, _greflect.Int8, _greflect.Int16, _greflect.Int32, _greflect.Int64:
		return map[string]any{"kind": "int", "goType": goType, "int": v.Int()}
	case _greflect.Uint, _greflect.Uint8, _greflect.Uint16, _greflect.Uint32, _greflect.Uint64:
		return map[string]any{"kind": "uint", "goType": goType, "uint": v.Uint()}
	case _greflect.String:
		return map[string]any{"kind": "string", "goType": goType, "str": v.String()}
	case _greflect.Array:
		elems := []any{}
		for i := 0; i < v.Len(); i++ {
			elems = append(elems, _gReflect(v.Index(i)))
		}
		return map[string]any{"kind": "array", "goType": goType, "len": v.Len(), "elems": elems}
	case _greflect.Slice:
		elems := []any{}
		for i := 0; i < v.Len(); i++ {
			elems = append(elems, _gReflect(v.Index(i)))
		}
		return map[string]any{"kind": "slice", "goType": goType, "len": v.Len(), "elems": elems}
	case _greflect.Map:
		// Keys SORTED: the deterministic full-map observation.
		keys := v.MapKeys()
		_gsort.Slice(keys, func(i, j int) bool {
			a, b := keys[i], keys[j]
			switch a.Kind() {
			case _greflect.String:
				return a.String() < b.String()
			case _greflect.Uint, _greflect.Uint8, _greflect.Uint16, _greflect.Uint32, _greflect.Uint64:
				return a.Uint() < b.Uint()
			case _greflect.Int, _greflect.Int8, _greflect.Int16, _greflect.Int32, _greflect.Int64:
				return a.Int() < b.Int()
			default:
				// Fail closed, not a.Int() on whatever arrived: a bool or
				// float key would panic INSIDE reflect with a misleading
				// message (audit H1 demonstrated exactly that).
				panic("grossmith driver: unsortable map key kind " + a.Kind().String())
			}
		})
		entries := []any{}
		for _, k := range keys {
			entries = append(entries, map[string]any{
				"key":   _gReflect(k),
				"value": _gReflect(v.MapIndex(k)),
			})
		}
		return map[string]any{"kind": "map", "goType": goType, "len": v.Len(), "entries": entries}
	case _greflect.Struct:
		fields := []any{}
		for i := 0; i < v.NumField(); i++ {
			fields = append(fields, map[string]any{
				"name":  v.Type().Field(i).Name,
				"value": _gReflect(v.Field(i)),
			})
		}
		return map[string]any{"kind": "struct", "goType": goType, "fields": fields}
	case _greflect.Interface:
		if v.IsNil() {
			// Fail closed, not emit-unparseable (mid-arc review finding
			// 5): a nil interface has no dynType/payload, and the old
			// empty-dynType emission was a document Parse REFUSES — a
			// protocol violation shipped by our own driver. The generator
			// invariant says interfaces are never nil; if it breaks, the
			// serialization-panic path (exit 3, audit H1) reports it as
			// infrastructure, never as a mangled observation.
			panic("grossmith driver: nil interface value — the never-nil generator invariant broke")
		}
		inner := v.Elem()
		return map[string]any{"kind": "interface", "goType": goType,
			"dynType": _gGoType(inner.Type()), "payload": _gReflect(inner)}
	}
	panic("grossmith driver: unobservable kind " + v.Kind().String())
}

func _gEmit(status string, ptrs []any, panicMsg string) {
	// A DRIVER defect must never be laundered into a subject observation
	// (audit H1): a serialization panic (unobservable kind, unsortable map
	// key) previously unwound into main's recover and was emitted as a
	// legitimate status:"panic" document with exit 0 — a fabricated
	// semantic outcome. Driver panics now exit 3 with no document; the
	// adapter reports run failure, which is infrastructure.
	defer func() {
		if r := recover(); r != nil {
			_gfmt.Fprintln(_gos.Stderr, "grossmith driver:", r)
			_gos.Exit(3)
		}
	}()
	doc := map[string]any{"schema": "grossmith-observation-v2", "status": status}
	if len(_gEvents) > 0 {
		doc["events"] = _gEvents
	}
	if status == "ok" {
		values := []any{}
		for _, p := range ptrs {
			values = append(values, _gValue(p))
		}
		doc["values"] = values
	}
	if status == "panic" {
		doc["panic"] = map[string]any{"kind": _gPanicKind(panicMsg), "message": panicMsg}
	}
	out, err := _gjson.Marshal(doc)
	if err != nil {
		_gfmt.Fprintln(_gos.Stderr, "grossmith driver: marshal:", err)
		_gos.Exit(3)
	}
	_gos.Stdout.Write(out)
	_gos.Stdout.Write([]byte("\n"))
}
`

// driverSource assembles the full generated driver: the static core plus a
// main that calls the subject with the observed tuple's arity.
func (g *Generator) driverSource(observed []binding) string {
	var out strings.Builder
	out.WriteString(driverCore)
	out.WriteString("\nfunc main() {\n")
	out.WriteString("\tdefer func() {\n")
	out.WriteString("\t\tif r := recover(); r != nil {\n")
	out.WriteString("\t\t\tmsg := \"\"\n")
	out.WriteString("\t\t\tif err, ok := r.(error); ok {\n")
	out.WriteString("\t\t\t\tmsg = err.Error()\n")
	out.WriteString("\t\t\t} else {\n")
	out.WriteString("\t\t\t\tmsg = _gfmt.Sprint(r)\n")
	out.WriteString("\t\t\t}\n")
	out.WriteString("\t\t\t_gEmit(\"panic\", nil, msg)\n")
	out.WriteString("\t\t}\n")
	out.WriteString("\t}()\n")
	rs := make([]string, len(observed))
	ptrs := make([]string, len(observed))
	for i := range observed {
		rs[i] = fmt.Sprintf("r%d", i)
		ptrs[i] = fmt.Sprintf("&r%d", i)
	}
	fmt.Fprintf(&out, "\t%s := %s()\n", strings.Join(rs, ", "), Subject)
	fmt.Fprintf(&out, "\t_gEmit(\"ok\", []any{%s}, \"\")\n", strings.Join(ptrs, ", "))
	out.WriteString("}\n")
	return out.String()
}
