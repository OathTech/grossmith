package main

import (
	"fmt"
	"os"
	"path/filepath"

	"grossmith/gen"
	"grossmith/harness"
	"grossmith/internal/strictjson"
)

// Construct profiles in the CLI (gc-verified arc G2). The profile file is
// read and validated before anything is written, applied to every case's
// config, checked against every case's recorded constructs, copied
// verbatim into the batch root (digested by the manifest), and named in
// every case.json. -verify re-derives all of it from the batch alone.

type loadedProfile struct {
	p   gen.Profile
	raw []byte
	sum string
}

// loadProfile reads a profile file; "" means no profile.
func loadProfile(path string) (*loadedProfile, error) {
	if path == "" {
		return nil, nil
	}
	raw, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("-profile: %w", err)
	}
	p, err := gen.ParseProfile(raw)
	if err != nil {
		return nil, fmt.Errorf("-profile %s: %w", path, err)
	}
	return &loadedProfile{p: p, raw: raw, sum: harness.SubjectHash(raw)}, nil
}

// ref is the case record's profile reference; nil without a profile.
func (l *loadedProfile) ref() *harness.ProfileRef {
	if l == nil {
		return nil
	}
	return &harness.ProfileRef{Name: l.p.Name, SHA256: l.sum}
}

// verifyProfile checks a verified batch against its profile.json, if it
// has one, and returns the profile's name ("" when there is none). For
// every case:
//
//   - case.json names this profile by name and digest;
//   - its recorded config excludes every tag the profile does not allow,
//     and forces (Include) none of them;
//   - its recorded subject features, and its battery functions' features,
//     use no optional construct outside the allow-list.
//
// Without profile.json, no case may name a profile. Inputs are already
// digest-checked by VerifyBatch; this checks what they claim.
func verifyProfile(root string, ids []string) (string, error) {
	raw, err := os.ReadFile(filepath.Join(root, harness.ProfileFile))
	hasProfile := err == nil
	if err != nil && !os.IsNotExist(err) {
		return "", err
	}
	var p gen.Profile
	sum := ""
	if hasProfile {
		if p, err = gen.ParseProfile(raw); err != nil {
			return "", fmt.Errorf("batch %s: %w", harness.ProfileFile, err)
		}
		sum = harness.SubjectHash(raw)
	}
	for _, id := range ids {
		b, err := os.ReadFile(filepath.Join(root, id, "case.json"))
		if err != nil {
			return "", err
		}
		var rec caseRecordIn
		if err := strictjson.Unmarshal(b, &rec); err != nil {
			return "", fmt.Errorf("%s/case.json: %w", id, err)
		}
		if !hasProfile {
			if rec.Profile != nil {
				return "", fmt.Errorf("%s/case.json names profile %s, but the batch has no %s", id, rec.Profile.Name, harness.ProfileFile)
			}
			continue
		}
		switch {
		case rec.Profile == nil:
			return "", fmt.Errorf("%s/case.json names no profile, but the batch was generated under %s", id, p.Name)
		case rec.Profile.Name != p.Name || rec.Profile.SHA256 != sum:
			return "", fmt.Errorf("%s/case.json names profile %s (%s), the batch's %s is %s (%s)", id,
				rec.Profile.Name, harness.ShortDigest(rec.Profile.SHA256), harness.ProfileFile, p.Name, harness.ShortDigest(sum))
		case rec.Config == nil:
			return "", fmt.Errorf("%s/case.json records no generator config", id)
		}
		excluded := map[string]bool{}
		for _, t := range rec.Config.Exclude {
			excluded[t] = true
		}
		for _, t := range p.Excluded() {
			if !excluded[t] {
				return "", fmt.Errorf("%s: config does not exclude %q, which profile %s does not allow", id, t, p.Name)
			}
		}
		for _, t := range rec.Config.Include {
			if !p.Allows(t) {
				return "", fmt.Errorf("%s: config forces %q, which profile %s does not allow", id, t, p.Name)
			}
		}
		if rec.Config.Constructs != nil {
			// The CLI never sets Constructs; a record that does was not
			// generated by this path, and the exclusion check above would
			// not describe it.
			return "", fmt.Errorf("%s: config sets an explicit construct map; profile batches use exclusions only", id)
		}
		c := gen.Case{FeatureCounts: rec.Features}
		if fp := filepath.Join(root, id, harness.FunctionsJSON); fileExists(fp) {
			d, err := harness.ReadFunctionsDoc(fp)
			if err != nil {
				return "", err
			}
			for _, f := range d.Functions {
				c.Functions = append(c.Functions, gen.BatteryFunction{Name: f.Function, Features: f.Features})
			}
		}
		if err := p.CheckFeatures(c); err != nil {
			return "", fmt.Errorf("%s: %w", id, err)
		}
	}
	return p.Name, nil
}

func fileExists(path string) bool {
	_, err := os.Lstat(path)
	return err == nil
}
